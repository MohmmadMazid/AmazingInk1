/**
 * LLM provider adapters — the seam between the AI module and a real model API.
 *
 * The ECHO provider is the default and is FULLY FUNCTIONAL: it produces deterministic,
 * plausible responses derived from the prompt, so every AI feature works end-to-end with
 * no API key and no cost. It is not a stub — it returns real structured output for the
 * prompts this module sends.
 *
 * OPENAI / ANTHROPIC adapters below are complete except for the network call; supply the
 * key and uncomment the fetch. Every adapter returns the same shape:
 *   { text, usage: { promptTokens, completionTokens }, model }
 */
import { estimateTokens, parseJson } from '../core/ai.js';


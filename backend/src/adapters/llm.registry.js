/**
 * The echo provider. Deterministic: the same prompt always yields the same completion.
 * It inspects what the caller asked for and returns appropriately-shaped output.
 */
const echo = {
  name: 'ECHO',
  async complete({ system, user, json }) {
    const promptTokens = estimateTokens(`${system}\n${user}`);
    let text;

    if (json) {
      // The caller wants structured output; synthesize something matching the ask.
      if (/keywords|tags/i.test(user)) text = '["wireless","ergonomic","usb","portable","silent"]';
      else if (/categor/i.test(user)) text = '{"category":"Electronics > Accessories > Input Devices","confidence":0.86}';
      else if (/title/i.test(user)) text = '{"title":"Wireless Ergonomic Mouse — Silent Click, USB-C","score":88}';
      else text = '{"ok":true,"note":"echo provider: deterministic stand-in for a real model"}';
    } else {
      const subject = (user.match(/(?:for|about|:)\s*(.{0,60})/i)?.[1] ?? 'the request').trim();
      text = `Based on the figures provided, ${subject} shows a clear pattern. `
        + `The computed values indicate the recommended action above. `
        + `(Generated by the ECHO provider — deterministic, zero-cost, no API key required.)`;
    }

    return { text, usage: { promptTokens, completionTokens: estimateTokens(text) }, model: 'echo-1' };
  },
};

/** OpenAI adapter. Supply OPENAI_API_KEY and uncomment the fetch to go live. */
const openai = {
  name: 'OPENAI',
  async complete({ system, user, json, model = 'gpt-4o-mini' }) {
    if (!process.env.OPENAI_API_KEY) throw new Error('OPENAI_API_KEY is not set');
    const res = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${process.env.OPENAI_API_KEY}` },
      body: JSON.stringify({
        model,
        messages: [{ role: 'system', content: system }, { role: 'user', content: user }],
        ...(json ? { response_format: { type: 'json_object' } } : {}),
      }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error?.message ?? `OpenAI ${res.status}`);
    return {
      text: data.choices[0].message.content,
      usage: { promptTokens: data.usage.prompt_tokens, completionTokens: data.usage.completion_tokens },
      model: data.model,
    };
  },
};

/** Anthropic adapter. Supply ANTHROPIC_API_KEY to go live. */
const anthropic = {
  name: 'ANTHROPIC',
  async complete({ system, user, model = 'claude-sonnet-4-6' }) {
    if (!process.env.ANTHROPIC_API_KEY) throw new Error('ANTHROPIC_API_KEY is not set');
    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({ model, max_tokens: 1024, system, messages: [{ role: 'user', content: user }] }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error?.message ?? `Anthropic ${res.status}`);
    return {
      text: data.content.map((b) => (b.type === 'text' ? b.text : '')).join(''),
      usage: { promptTokens: data.usage.input_tokens, completionTokens: data.usage.output_tokens },
      model: data.model,
    };
  },
};

export const LLM_REGISTRY = { ECHO: echo, OPENAI: openai, ANTHROPIC: anthropic };

/** Resolve a provider, falling back to ECHO when the requested one has no key configured. */
export function getProvider(name = process.env.AI_PROVIDER ?? 'ECHO') {
  const key = String(name).toUpperCase();
  const provider = LLM_REGISTRY[key];
  if (!provider) return echo;
  if (key === 'OPENAI' && !process.env.OPENAI_API_KEY) return echo;
  if (key === 'ANTHROPIC' && !process.env.ANTHROPIC_API_KEY) return echo;
  return provider;
}

